package KI306.Kusmyna.Lab6;

/**
 * Інтерфейс предметної області «Споруда».
 *
 * <p>Споруди можна порівнювати між собою для пошуку максимального елемента
 * у контейнері (варіант 9 — непарний).</p>
 */
public interface Structure extends Comparable<Structure> {

    /**
     * Повертає назву споруди.
     *
     * @return назва споруди
     */
    String getName();

    /**
     * Повертає числову метрику споруди, за якою здійснюється порівняння.
     * <p>Чим більша метрика — тим “більша” споруда.</p>
     *
     * @return значення метрики
     */
    double getMetric();

    /**
     * Повертає назву метрики (для відображення користувачу).
     *
     * @return назва метрики
     */
    String metricName();

    /**
     * Виводить інформацію про споруду в консоль.
     */
    void printInfo();
}
