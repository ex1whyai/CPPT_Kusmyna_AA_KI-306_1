# Лабораторна №7 — варіант 9
# Формування зубчатого списку із заштрихованої області квадратної матриці.
# Заштрихована область (варіант 9): верхньо-ліва трикутна область відносно
# побічної діагоналі (знизу-ліворуч -> вгору-праворуч), включно з діагоналлю.

import sys


def build_jagged_variant9(n: int, filler: str) -> list[list[str]]:
    """
    Повертає зубчатий список для варіанту 9.
    Умову заштрихованої області можна записати так: i + j <= n - 1.
    Для кожного рядка i це означає: j = 0 .. (n-1-i), тобто (n-i) елементів.
    """
    jagged: list[list[str]] = []
    for i in range(n):
        # у рядку i зберігаємо тільки перші (n - i) елементів (заштрихована частина)
        jagged.append([filler] * (n - i))
    return jagged


def print_jagged(jagged: list[list[str]]) -> None:
    """Друк зубчатого списку у вигляді рядків."""
    for row in jagged:
        print(" ".join(row))


def main() -> None:
    # Ввід розміру матриці
    try:
        n = int(input("Введіть розмір квадратної матриці n: "))
    except ValueError:
        print("Помилка: n має бути цілим числом.")
        sys.exit(1)

    if n <= 0:
        print("Помилка: n має бути додатнім.")
        sys.exit(1)

    # Ввід символу-заповнювача
    filler = input("Введіть символ-заповнювач (1 символ): ")

    # Коректне переривання при не введенні або введенні кількох символів
    if len(filler) == 0:
        print("Не введено символ-заповнювач.")
        sys.exit(1)
    if len(filler) != 1:
        print("Забагато символів-заповнювачів (потрібен рівно 1).")
        sys.exit(1)

    # Формування та вивід
    jagged = build_jagged_variant9(n, filler)
    print("\nСформований зубчатий список (варіант 9):")
    print_jagged(jagged)


if __name__ == "__main__":
    main()
